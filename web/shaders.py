#!/usr/bin/env python3
"""Turns the shaders a Goose program embeds into GLSL ES 3.00 for WebGL 2.

embed_shader() compiles each shader into a blob of SPIR-V, MSL and HLSL
(src/gfx/gfx_blob.h in the Goose source), which the generated C holds as
`static const uint8_t gs_blobN[...] = { ... };`. This reads those arrays from
the C file, hands each blob's SPIR-V to spirv-cross, and writes a C table the
web gfx layer (gfx_web.c) looks blobs up in by their hash:

    shaders.py game.c shaders_web.c [spirv-cross]

Varyings are renamed by location, since GLSL ES links them by name; uniform
blocks and samplers are listed by binding, since GLSL ES 3.00 has no binding
qualifiers.
"""

import json
import os
import re
import struct
import subprocess
import sys
import tempfile

HEADER = struct.Struct("<4sHBB3I6H6I")


def fnv1a(data):
    h = 14695981039346656037
    for b in data:
        h = ((h ^ b) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def blobs(c_text):
    for m in re.finditer(r"static const uint8_t (gs_blob\d+)\[(\d+)\] = \{([^}]*)\};", c_text):
        data = bytes(int(x) for x in m.group(3).replace("\n", " ").split(",") if x.strip())
        assert len(data) == int(m.group(2)), m.group(1)
        if data[:4] == b"GSHD":
            yield m.group(1), data


def c_string(s):
    out = []
    for line in s.splitlines():
        out.append('"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    return "\n    ".join(out)


def convert(name, blob, spirv_cross, tmp):
    (magic, version, stage, ninputs, _lx, _ly, _lz, nsamp, _a, _b, _c, _d, nubo,
     spv_off, spv_size, _mo, _ms, _ho, _hs) = HEADER.unpack_from(blob)
    if stage > 1:
        return None  # compute: WebGL 2 has none
    spv = os.path.join(tmp, name + ".spv")
    with open(spv, "wb") as f:
        f.write(blob[spv_off:spv_off + spv_size])
    reflect = json.loads(subprocess.check_output([spirv_cross, spv, "--reflect"]))
    args = [spirv_cross, spv, "--es", "--version", "300", "--remove-unused-variables"]
    # Varyings by location: v<location>, the same name on both sides.
    side = "out" if stage == 0 else "in"
    for io in reflect.get("outputs" if stage == 0 else "inputs", []):
        args += ["--rename-interface-variable", side, str(io["location"]), "gs_v%d" % io["location"]]
    glsl = subprocess.check_output(args).decode()
    # Full float precision: the shapes are signed distances in pixels.
    glsl = glsl.replace("precision mediump float;", "precision highp float;")
    glsl = glsl.replace("precision mediump int;", "precision highp int;")
    ubos = ["" for _ in range(nubo)]
    for u in reflect.get("ubos", []):
        ubos[u["binding"]] = u["name"]
    samplers = ["" for _ in range(nsamp)]
    for t in reflect.get("textures", []):
        samplers[t["binding"]] = t["name"]
    return stage, glsl, ubos, samplers


def main():
    src, out = sys.argv[1], sys.argv[2]
    spirv_cross = sys.argv[3] if len(sys.argv) > 3 else "spirv-cross"
    with open(src) as f:
        text = f.read()
    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, blob in blobs(text):
            r = convert(name, blob, spirv_cross, tmp)
            if r:
                entries.append((name, fnv1a(blob), len(blob)) + r)
    lines = [
        "/* Generated by web/shaders.py from the program's embedded shaders. */",
        "#include \"shaders_web.h\"",
        "",
        "const gs_web_shader gs_web_shaders[] = {",
    ]
    for name, h, size, stage, glsl, ubos, samplers in entries:
        def names(xs):
            return "{ " + ", ".join('"%s"' % x for x in (xs + ["", "", "", ""])[:4]) + " }"
        lines += [
            "    /* %s */" % name,
            "    { 0x%016xull, %d, %d, %s, %s,\n    %s }," % (h, size, stage, names(ubos), names(samplers),
                                                          c_string(glsl)),
        ]
    lines += ["};", "", "const int gs_web_shader_count = %d;" % len(entries), ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
